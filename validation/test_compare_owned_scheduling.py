def mutate(path, edit):
    document = json.loads(path.read_text(encoding="utf-8"))
    edit(document)
    write(path, json.dumps(document))


def make_pair(tmp_path, *, sb="1", sa="1", bb="boot-abc", ba="boot-abc",
              t100b=None, t100a=None):
    children = worker_children(tmp_path)
    pb = base_tree(tmp_path / "b", [t100b or thread(100)], schedstats=sb,
                   boot_id=bb)
    pa = base_tree(tmp_path / "a", [t100a or thread(100)], schedstats=sa,
                   boot_id=ba)
    clock = TickingClock()
    snapshot(pb, children, tmp_path / "before.json", clock, "before")
    snapshot(pa, children, tmp_path / "after.json", clock, "after")
    return tmp_path / "before.json", tmp_path / "after.json"


def compare_pair(before, after, output="delta.json"):
    return SnapshotComparison(before, after, before.parent / output).compare()


@pytest.mark.parametrize("value", ["xyz", 123, None])
def test_invalid_children_sha_unbinds(tmp_path, value):
    before, after = make_pair(tmp_path)

