def test_output_exclusive_and_inputs_untouched(tmp_path):
    children = worker_children(tmp_path)
    proc = base_tree(tmp_path / "b", [thread(100)])
    clock = TickingClock()
    before = tmp_path / "before.json"
    after = tmp_path / "after.json"
    snapshot(proc, children, before, clock, "before")
    snapshot(proc, children, after, clock, "after")
    before_sha = hashlib.sha256(before.read_bytes()).hexdigest()
    after_sha = hashlib.sha256(after.read_bytes()).hexdigest()

    output = tmp_path / "delta.json"
    SnapshotComparison(before, after, output).compare()
    first = output.read_bytes()
    with pytest.raises(FileExistsError):
        SnapshotComparison(before, after, output).compare()

    assert output.read_bytes() == first
    assert hashlib.sha256(before.read_bytes()).hexdigest() == before_sha
    assert hashlib.sha256(after.read_bytes()).hexdigest() == after_sha


