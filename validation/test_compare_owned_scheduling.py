    snapshot(proc, children_b, tmp_path / "after.json", clock, "after")

    result = SnapshotComparison(tmp_path / "before.json", tmp_path / "after.json",
                                tmp_path / "delta.json").compare()

    assert result["binding"]["status"] == "unbound"
    assert "children_sha256_mismatch" in result["binding"]["reasons"]
    assert result["roles"] == {}
    assert (tmp_path / "delta.json").exists()
    assert result["performance_verdict"] == "not_evaluated"


