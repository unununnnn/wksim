class TickingClock:
    """Strictly increasing monotonic clock shared across both captures."""

    def __init__(self):
        self.ns = 0

    def __call__(self):
        self.ns += 1_000_000
        return {"wall_utc": "2026-09-13T00:00:00+00:00",
                "monotonic_ns": self.ns, "boottime_ns": None}


def snapshot(proc_root, children, path, clock, phase, reader=None):
    capture = OwnedSchedulingCapture(
        children, path, phase=phase, proc_root=proc_root, clock_ticks=100,
        now=clock, reader=reader)
    return capture.capture()


def thread(tid, *, utime=10, stime=20, schedstat=(111, 222, 3),
           start_ticks=500, rt_priority=40, policy=1,
           sched="policy : 1\nprio : 59\n"):
    return {"tid": tid, "comm": f"t{tid}", "state": "S",
            "start_ticks": start_ticks, "utime": utime, "stime": stime,
            "schedstat": schedstat, "rt_priority": rt_priority,
            "policy": policy, "sched": sched}


def base_tree(root, threads, *, schedstats="1", boot_id="boot-abc"):
    proc = build_proc_tree(root, [
        {"pid": 100, "pgid": 100, "start_ticks": 500, "comm": "worker",
         "threads": threads}], schedstats=schedstats)
    if boot_id is not None:
        write(proc / "sys/kernel/random/boot_id", boot_id + "\n")
    return proc


def set_switches(proc_root, tid, voluntary, nonvoluntary, cpus="0-7"):
    write(proc_root / "100" / "task" / str(tid) / "status",
          f"Cpus_allowed_list:\t{cpus}\n"
          f"voluntary_ctxt_switches:\t{voluntary}\n"
          f"nonvoluntary_ctxt_switches:\t{nonvoluntary}\n")


def worker_children(tmp_path, extra=None):
    entries = {"worker-a": {"identity": {"pid": 100, "pgid": 100,
                                         "start_ticks": 500,
                                         "argv": ["/usr/bin/python3", "-m", "worker"]}}}
    if extra:
        entries.update(extra)
    return make_children(tmp_path, entries)


def run_compare(tmp_path, proc_b, proc_a, children, *, reader_after=None,
                output="delta.json"):
    clock = TickingClock()
    snapshot(proc_b, children, tmp_path / "before.json", clock, "before")
    snapshot(proc_a, children, tmp_path / "after.json", clock, "after",
             reader=reader_after)
    return SnapshotComparison(tmp_path / "before.json", tmp_path / "after.json",
                              tmp_path / output).compare()


def test_bound_comparison_hand_computed_deltas(tmp_path):
    children = worker_children(tmp_path)
    proc_b = base_tree(tmp_path / "b", [
        thread(100, utime=10, stime=20, schedstat=(111, 222, 3)),
        thread(101, utime=30, stime=40, schedstat=(50, 60, 2))])
    proc_a = base_tree(tmp_path / "a", [
        thread(100, utime=25, stime=24, schedstat=(311, 322, 8)),
        thread(101, utime=30, stime=40, schedstat=(50, 60, 2))])
    set_switches(proc_b, 100, 3, 0)
    set_switches(proc_b, 101, 1, 1)
    set_switches(proc_a, 100, 9, 2)
    set_switches(proc_a, 101, 1, 1)

    result = run_compare(tmp_path, proc_b, proc_a, children)

    assert result["schema"] == "wksim.owned-scheduling-comparison.v1"
    assert result["binding"]["status"] == "bound"
    assert result["binding"]["reasons"] == []
    assert result["binding"]["monotonic_delta_ns"] > 0
    assert result["performance_verdict"] == "not_evaluated"
    assert result["attribution"] == "not_evaluated"

    role = result["roles"]["worker-a"]
    assert role["status"] == "compared"
    assert role["threads_compared"] == 2
    assert role["threads_unavailable"] == 0

    rows = {row["tid"]: row for row in role["compared_threads"]}
    assert rows[100]["delta"] == {
        "utime_ticks": 15, "stime_ticks": 4, "run_ns": 200,
        "runqueue_ns": 100, "timeslices": 5,
        "voluntary_ctxt_switches": 6, "nonvoluntary_ctxt_switches": 2}
    assert rows[100]["negative_counters"] == []
    assert rows[100]["delta_unavailable"] == {}
    transitions = rows[100]["transitions"]
    assert transitions["rt_priority"] == {"before": 40, "after": 40,
                                          "changed": False}
    assert transitions["kernel_prio"]["before"] == 59
    assert "not" in transitions["kernel_prio"]["note"].lower()
    assert transitions["cpus_allowed_list"]["changed"] is False

    # A genuinely unchanged counter yields 0, not null.
    assert rows[101]["delta"] == {
        "utime_ticks": 0, "stime_ticks": 0, "run_ns": 0, "runqueue_ns": 0,
        "timeslices": 0, "voluntary_ctxt_switches": 0,
        "nonvoluntary_ctxt_switches": 0}


def test_children_sha_mismatch_unbinds_and_writes_report(tmp_path):
    worker_children(tmp_path)  # children-start.json (before)
    children_b = tmp_path / "children-b.json"
